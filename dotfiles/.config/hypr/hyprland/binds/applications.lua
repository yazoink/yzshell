	hl.bind("SUPER + ALT + S", hl.dsp.exec_cmd("yzwidgets close all"))
end)

hl.define_submap("settings", function()
	hl.bind("escape", hl.dsp.exec_cmd("yzwidgets close all"))
	hl.bind("SUPER + SHIFT + A", hl.dsp.exec_cmd("yzwidgets close all"))
end)

hl.define_submap("workspaces", function()
	hl.bind("escape", hl.dsp.exec_cmd("yzwidgets close all"))
	hl.bind("Tab", hl.dsp.exec_cmd("yzwidgets close all"))
	hl.bind("SUPER + Tab", hl.dsp.exec_cmd("yzwidgets close all"))
	hl.bind("Return", hl.dsp.exec_cmd("yzwidgets close all"))
	hl.bind("left", function()
		hl.dispatch(hl.dsp.focus({ workspace = "e-1" }))
		hl.dispatch(hl.dsp.exec_cmd("eww poll workspaces"))
		hl.dispatch(hl.dsp.exec_cmd("eww poll active_workspace"))
	end)
	hl.bind("right", function()
		hl.dispatch(hl.dsp.focus({ workspace = "e+1" }))
		hl.dispatch(hl.dsp.exec_cmd("eww poll workspaces"))
		hl.dispatch(hl.dsp.exec_cmd("eww poll active_workspace"))
	end)
	hl.bind("up", function()
		hl.dispatch(hl.dsp.focus({ workspace = "e-1" }))
		hl.dispatch(hl.dsp.exec_cmd("eww poll workspaces"))
		hl.dispatch(hl.dsp.exec_cmd("eww poll active_workspace"))
	end)
	hl.bind("down", function()
		hl.dispatch(hl.dsp.focus({ workspace = "e+1" }))
		hl.dispatch(hl.dsp.exec_cmd("eww poll workspaces"))
		hl.dispatch(hl.dsp.exec_cmd("eww poll active_workspace"))
	end)
	for i = 1, 9 do
		hl.bind("SUPER + " .. i, function()
			hl.dispatch(hl.dsp.exec_cmd("eww poll workspaces"))
			hl.dispatch(hl.dsp.exec_cmd("eww poll active_workspace"))
			hl.dispatch(hl.dsp.focus({ workspace = i }))
		end)
		hl.bind(i, function()
			hl.dispatch(hl.dsp.exec_cmd("eww poll workspaces"))
			hl.dispatch(hl.dsp.exec_cmd("eww poll active_workspace"))
			hl.dispatch(hl.dsp.focus({ workspace = i }))
			hl.dispatch(hl.dsp.exec_cmd("yzwidgets close all"))
		end)
	end
end)
