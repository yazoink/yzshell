hl.define_submap("control_center", function()
	hl.bind("escape", hl.dsp.exec_cmd("yzwidgets close all"))
	hl.bind("up", hl.dsp.exec_cmd("yzwidgets ctl control_center_search_selected prev"))
	hl.bind("down", hl.dsp.exec_cmd("yzwidgets ctl control_center_search_selected next"))
	hl.bind("SUPER + P", hl.dsp.exec_cmd("yzwidgets close all"))
end)

hl.define_submap("calendar", function()
	hl.bind("escape", hl.dsp.exec_cmd("yzwidgets close all"))
	hl.bind("SUPER + SHIFT + C", hl.dsp.exec_cmd("yzwidgets close all"))
end)

hl.define_submap("power", function()
	hl.bind("escape", hl.dsp.exec_cmd("yzwidgets close all"))
	hl.bind("l", hl.dsp.exec_cmd("yzwidgets close all; yzlock -g 0"))
	hl.bind("s", hl.dsp.exec_cmd("systemctl shutdown"))
	hl.bind("r", hl.dsp.exec_cmd("systemctl reboot"))
	hl.bind("e", hl.dsp.exec_cmd("hyprctl dispatch 'hl.dsp.exit()'"))
	hl.bind("SUPER + SHIFT + Q", hl.dsp.exec_cmd("yzwidgets close all"))
end)

